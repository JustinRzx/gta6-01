// Saving and restoring progress (money and jobs done) to localStorage. Storage
// can be off in private windows, so reads and writes never throw.
import { SAVE_KEY } from './config.js';

export function loadSave() {
  try {
    const raw = window.localStorage.getItem(SAVE_KEY);
    if (!raw) return null;
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

export function writeSave(data) {
  try {
    window.localStorage.setItem(SAVE_KEY, JSON.stringify(data));
  } catch {
    // ignored: the save simply lasts this visit only
  }
}
